"""Scenario Definitions and Dataclasses for the Synthetic Validation Harness."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class AnomalyCategory(str, Enum):
    """Broad categorization of synthetic validation scenarios."""
    BASELINE = "BASELINE"
    TEMPORAL_FAULT = "TEMPORAL_FAULT"
    PHYSICAL_LIMIT = "PHYSICAL_LIMIT"
    DATA_QUALITY = "DATA_QUALITY"
    MULTIVARIATE_FAULT = "MULTIVARIATE_FAULT"
    SPATIAL_FAULT = "SPATIAL_FAULT"
    GENUINE_METEOROLOGICAL_EVENT = "GENUINE_METEOROLOGICAL_EVENT"
    SOURCE_OR_NETWORK_OUTAGE = "SOURCE_OR_NETWORK_OUTAGE"


@dataclass
class ScenarioDefinition:
    """Authoritative metadata and expectations for a single synthetic validation scenario."""
    scenario_id: str
    name: str
    category: AnomalyCategory
    target_stations: List[str]
    description: str
    injection_start_step: int
    injection_end_step: int
    anomaly_type: str
    parameters: Dict[str, Any] = field(default_factory=dict)
    
    # Explicit 9-Dimensional Expectation Specifications
    expected_detection: bool = False
    expected_decision: str = "NORMAL"
    accepted_decisions: List[str] = field(default_factory=lambda: ["NORMAL"])
    expected_sensor_health_direction: str = "STABLE"  # STABLE, DECREASING, PROTECTED, RECOVERING
    expected_source_health: str = "HEALTHY"           # HEALTHY, DEGRADED, DISCONNECTED, STALE
    expected_correction: str = "NONE"                 # NONE, GENERATED
    expected_persistence: bool = True
    expected_websocket: bool = True
    
    # Metadata & Transport expectations
    expected_ws_event_type: str = "OBSERVATION_UPDATED"
    expected_qc_status: str = "VALID"
    isolation_expected: bool = True

    def to_dict(self) -> Dict[str, Any]:
        """Convert scenario definition to dictionary."""
        d = asdict(self)
        d["category"] = self.category.value
        return d


