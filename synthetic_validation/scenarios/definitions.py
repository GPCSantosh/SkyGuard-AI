def get_scenario_by_id(scenario_id: str) -> Optional[ScenarioDefinition]:
    """Retrieve scenario definition by its SV identifier."""
    sid = scenario_id.upper().strip()
    for sc in SCENARIO_DEFINITIONS:
        if sc.scenario_id == sid:
            return sc
    return None
